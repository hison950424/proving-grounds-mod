def shade(rgb, f):
    return tuple(max(0, min(255, int(c * f))) for c in rgb)

def png(path, rows, size=16):
    raw = b"".join(b"\x00" + b"".join(struct.pack("BBBB", *px) for px in row) for row in rows)
    def chunk(t, d):
        return struct.pack(">I", len(d)) + t + d + struct.pack(">I", zlib.crc32(t + d) & 0xffffffff)
    data = b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", size, size, 8, 6, 0, 0, 0)) \
        + chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b"")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "wb") as f:
        f.write(data)

def render(shape, rgb, alpha=255):
    lines = [l for l in SHAPES[shape].strip("\n").split("\n")]
    assert len(lines) == 16, shape
    pal = {"#": rgb, "o": shade(rgb, 0.35), "+": shade(rgb, 1.6) if max(rgb) < 160 else (255, 255, 255),
           "w": (245, 245, 245), "k": (20, 20, 24)}
    rows = []
    for l in lines:
        l = l.ljust(16, ".")[:16]
        rows.append([(0, 0, 0, 0) if ch == "." else (*pal[ch], alpha) for ch in l])
    return rows

def main():
    src = open(os.path.join(ROOT, "java", "com", "provinggrounds", "special", "SpecialType.java"), encoding="utf-8").read()
    items = re.findall(r'^\s+[A-Z_]+\("([a-z_]+)", "[^"]+", "[^"]+", "[^"]+", 0x([0-9A-F]+)\)', src, re.M)
    # knockback_shield_held 用原版盾牌模型（ShieldItemRenderer），不需要貼圖
    for iid, hexcol in items:
        v = int(hexcol, 16)
        rgb = ((v >> 16) & 255, (v >> 8) & 255, v & 255)
        if max(rgb) < 60: rgb = (70, 70, 80)  # 太暗的顏色（致盲珠）稍微提亮，外框才看得出來
        png(os.path.join(OUT, iid + ".png"), render(CATEGORY[iid], rgb))
    # 效果圖示（18x18，畫在物品欄的效果清單）
    effects = {"concussion": ("star", (190, 190, 190)), "cloak": ("cloak", (128, 128, 192)), "adrenaline": ("syringe", (224, 64, 64)),
               "silent": ("boots", (64, 64, 96)), "shield_bubble": ("ring", (96, 192, 255)), "bubble_speed": ("ring", (96, 192, 255)),
               "zone_shelter": ("ring", (192, 240, 192)), "gassed": ("orb", (96, 192, 32)), "totem_held": ("totem", (240, 208, 64)),
               "brainwash": ("brain", (192, 64, 192)), "downed": ("person", (160, 40, 40)), "stim_free": ("syringe", (224, 64, 64)), "rooted": ("orb", (80, 224, 176))}
    for name, (shape, rgb) in effects.items():
        rows = [[(0, 0, 0, 0)] * 18] + [[(0, 0, 0, 0)] + r + [(0, 0, 0, 0)] for r in render(shape, rgb)] + [[(0, 0, 0, 0)] * 18]
        png(os.path.join(ROOT, "resources", "assets", "provinggrounds", "textures", "mob_effect", name + ".png"), rows, 18)
    # 特殊物品欄的提示圖示：淡淡的星形
    png(os.path.join(GUI, "slot_special.png"), render("star", (200, 200, 210), 110))
    print("ok", len(items))

main()
